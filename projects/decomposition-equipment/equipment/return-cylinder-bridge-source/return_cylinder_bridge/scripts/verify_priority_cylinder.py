#!/usr/bin/env python3
"""Independent finite checks; no dependencies, raw tensor construction, or physical intervention claim."""
from itertools import product, permutations, combinations
import json
from pathlib import Path
N=4
ROLES=(0,1,0,1)
EDGES=((0,3),(1,2))
WORDS=list(product((0,1),repeat=N))
OUTPUTS=list(product((0,1),repeat=2))
def parity(r,b):
    return tuple(sum(b[r[j]-1] for j in range(N) if ROLES[j]==a)%2 for a in range(2))
RANKS=list(permutations(range(1,N+1)))
valid=[r for r in RANKS if all(r[i]<r[j] for i,j in EDGES)]
marginals=[{r[i] for r in valid} for i in range(N)]
relaxed=[r for r in RANKS if all(r[i] in marginals[i] for i in range(N))]
exact={b:frozenset(parity(r,b) for r in valid) for b in WORDS}
marginal={b:frozenset(parity(r,b) for r in relaxed) for b in WORDS}
def closure(rows):
    ans={frozenset()}
    for row in rows: ans|={x|row for x in list(ans)}
    return ans
A=closure(exact.values()); B=closure(marginal.values())
# Explicit Boolean-module map q generated by the three disjoint atoms of A.
zero=frozenset({(0,0)}); one=frozenset({(1,1)}); odd=frozenset({(0,1),(1,0)})
def q(s):
    return frozenset().union(*(target for atom,target in [(zero,zero),(one,zero|one),(odd,odd)] if atom<=s))
assert len(A)==8 and len(B)==6
assert all(q(exact[b])==marginal[b] for b in WORDS)
assert all(q(s|t)==q(s)|q(t) for s in A for t in A)
assert all(s<=q(s) for s in A)
assert B<=A
pairs=closure(frozenset((('joint',)+y) for y in exact[b]) | frozenset((('marginal',)+y) for y in marginal[b]) for b in WORDS)
assert len(pairs)==8
print(json.dumps({'joint_middle_size':len(A),'marginal_middle_size':len(B),'combined_test_apex_size':len(pairs),'exact_0011':sorted(exact[(0,0,1,1)]),'marginal_0011':sorted(marginal[(0,0,1,1)]),'q_prep_compatible_join_preserving':True,'q_test_preserving':False,'inclusion_test_preserving':True,'inclusion_prep_compatible':False},indent=2))

# Relational factors carry COMPLETE joint scopes. Projection only occurs once
# every factor mentioning an eliminated variable has been joined.
def factor(scope,predicate,domains):
    return (tuple(scope),{v for v in product(*(domains[x] for x in scope)) if predicate(*v)})
def join(f,g):
    fs,fr=f; gs,gr=g
    shared=[x for x in fs if x in gs]
    fi=[fs.index(x) for x in shared]; gi=[gs.index(x) for x in shared]
    extra=[k for k,x in enumerate(gs) if x not in fs]
    index={}
    for t in gr: index.setdefault(tuple(t[k] for k in gi),[]).append(t)
    return fs+tuple(gs[k] for k in extra),{s+tuple(t[k] for k in extra) for s in fr for t in index.get(tuple(s[k] for k in fi),[])}
def project(f,x):
    scope,rows=f; k=scope.index(x)
    return scope[:k]+scope[k+1:],{s[:k]+s[k+1:] for s in rows}
def eliminate(factors,order):
    factors=list(factors)
    for x in order:
        relevant=[f for f in factors if x in f[0]]
        factors=[f for f in factors if x not in f[0]]
        if relevant:
            f=relevant[0]
            for g in relevant[1:]: f=join(f,g)
            factors.append(project(f,x))
    f=((),{()})
    for g in factors: f=join(f,g)
    assert not f[0]
    return bool(f[1])
def primitive_factors(b,y):
    domains={**{'r'+str(i):range(1,N+1) for i in range(N)},**{'c'+str(i):(0,1) for i in range(N)}}
    ans=[factor(('r'+str(i),'r'+str(j)),lambda x,z:x!=z,domains) for i,j in combinations(range(N),2)]
    ans += [factor(('r'+str(i),'r'+str(j)),lambda x,z:x<z,domains) for i,j in EDGES]
    ans += [factor(('r'+str(i),'c'+str(i)),lambda r,c:c==b[r-1],domains) for i in range(N)]
    # A two-input XOR is the length-two chain with initial state 0;
    # other intermediate states are uniquely determined and thus substituted.
    ans += [factor(tuple('c'+str(i) for i in range(N) if ROLES[i]==a),lambda *cs,a=a:sum(cs)%2==y[a],domains) for a in range(2)]
    return ans
orders=[['c'+str(i) for i in range(N)]+['r'+str(i) for i in range(N)],['r'+str(i) for i in reversed(range(N))]+['c'+str(i) for i in reversed(range(N))],['r0','c0','r2','c2','r1','c1','r3','c3']]
for b,y in product(WORDS,OUTPUTS):
    fs=primitive_factors(b,y)
    direct=any(all(r[i]!=r[j] for i,j in combinations(range(N),2)) and all(r[i]<r[j] for i,j in EDGES) and parity(r,b)==y for r in product(range(1,N+1),repeat=N))
    assert direct==(y in exact[b])
    assert all(eliminate(fs,order)==direct for order in orders)

# Polynomial certificate: transitive closure + adjacent transition prefixes.
def reachability(n,edges):
    reach=[[False]*n for _ in range(n)]
    for i,j in edges: reach[i][j]=True
    for k in range(n):
        for i in range(n):
            for j in range(n): reach[i][j] |= reach[i][k] and reach[k][j]
    return reach
def certificate(n,roles,edges,b):
    reach=reachability(n,edges)
    if any(reach[i][i] for i in range(n)): return 'INCONSISTENT'
    pred=[{j for j in range(n) if reach[j][i]} for i in range(n)]
    succ=[{j for j in range(n) if reach[i][j]} for i in range(n)]
    prefix=[0]
    for k in range(n-1): prefix.append(prefix[-1]+(b[k]!=b[k+1]))
    for i,j in combinations(range(n),2):
        if roles[i]!=roles[j] and not reach[i][j] and not reach[j][i]:
            lo=len(pred[i]|pred[j])+1; hi=n-len(succ[i]|succ[j])-1
            if prefix[hi]-prefix[lo-1]: return 'UNRESOLVED'
    return 'PASS'
# Enumerate distinct labelled four-job posets independently via all topological
# labellings of every forward-edge graph, then check all observed bit words.
posets=set()
forward=list(combinations(range(N),2))
for mask in range(1<<len(forward)):
    edges=[e for k,e in enumerate(forward) if mask>>k&1]
    reach=reachability(N,edges)
    for perm in permutations(range(N)):
        posets.add(tuple(sorted((perm[i],perm[j]) for i in range(N) for j in range(N) if reach[i][j])))
for edges in posets:
    rs=[r for r in RANKS if all(r[i]<r[j] for i,j in edges)]
    for b in WORDS:
        assert (certificate(N,ROLES,edges,b)=='PASS')==(len({parity(r,b) for r in rs})==1)
assert certificate(N,ROLES,((0,1),(1,0)),WORDS[0])=='INCONSISTENT'

# Pair-row apex projections are surjective join maps and preparation-compatible.
def pi(s,label): return frozenset(t[1:] for t in s if t[0]==label)
assert {pi(s,'joint') for s in pairs}==A
assert {pi(s,'marginal') for s in pairs}==B
assert all(pi(s,'marginal')==q(pi(s,'joint')) for s in pairs)
assert len({pi(s,'joint') for s in pairs})==len(pairs)
# Splitting the common rank witness at the two role output ports produces
# {0,1}x{0,1} only if each bit can occur; for b=0011 it cannot: both true
# marginals are singleton 1. The applicable false witness comes from splitting
# job-wise rank occurrences / projecting the edge-and-all-different relation.
b=(0,0,1,1); false_r=(1,3,2,4)
assert all(false_r[i] in marginals[i] for i in range(N))
assert not all(false_r[i]<false_r[j] for i,j in EDGES)
assert parity(false_r,b)==(0,0)
# Each job rank has its own *different* legal witness, no common legal one.
separate_witnesses=[next(r for r in valid if r[i]==false_r[i]) for i in range(N)]
assert all(separate_witnesses[i][i]==false_r[i] for i in range(N))

actual_support=frozenset((b,y) for b in WORDS for y in exact[b])
assert len(closure([actual_support]))==2
assert {q(s) for s in A}==B

def render(s): return [''.join(map(str,t)) for t in sorted(s)]
results={
 'primitive_network':{'n':N,'roles':ROLES,'edges':EDGES,'valid_rank_assignments':valid,'marginal_rank_assignments':relaxed,'joint_kernel_entries_checked':64,'elimination_orders_checked':orders,'all_factor_checks_pass':True},
 'middles':{'joint_size':len(A),'marginal_size':len(B),'joint':sorted([render(s) for s in A]),'marginal':sorted([render(s) for s in B]),'combined_apex_size':len(pairs)},
 'rows':[{'b':''.join(map(str,b)),'joint':render(exact[b]),'marginal':render(marginal[b])} for b in WORDS],
 'maps':{'q_join_preserving':True,'q_preparation_preserving':True,'q_test_preserving':False,'q_extensive':True,'inclusion_join_preserving':True,'inclusion_test_preserving':True,'inclusion_preparation_preserving':False,'combined_apex_projections_surjective':True,'combined_joint_projection_isomorphism':True},
 'certificate':{'distinct_labelled_posets':len(posets),'words_per_poset':len(WORDS),'exhaustive_checks':len(posets)*len(WORDS),'cycle_rejected':True,'fixture_accepts_0011':certificate(N,ROLES,EDGES,(0,0,1,1))=='PASS'},
 'split_witness':{'false_rank_vector':false_r,'different_legal_witness_per_job':separate_witnesses,'false_output':'00','true_output':'11'},
 'actual_profile_middle_size':2,
 'scope':'Finite conditional Boolean support checks. No raw tensor carrier enumerated; no physical preparation of b; no proof of general full-record equality.'}
out=Path(__file__).with_name('verification_results.json')
out.write_text(json.dumps(results,indent=2)+'\n')
print('PASS:',len(posets)*len(WORDS),'certificate comparisons; 64 primitive kernel cells x 3 elimination orders;',out)
