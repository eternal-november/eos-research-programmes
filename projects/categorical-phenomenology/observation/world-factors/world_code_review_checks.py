#!/usr/bin/env python3
"""Independent rational checks of affine support and stopped-transcript claims.

Python 3.10+ only. No third-party packages or network access.
This uses its own enumeration rather than importing the original check scripts.
"""
from collections import Counter
from fractions import Fraction as F
from pathlib import Path
import json


def dot(x, y):
    return (x & y).bit_count() % 2


def spaces(m):
    out = {frozenset({0})}
    pending = list(out)
    while pending:
        v = pending.pop()
        for x in range(1 << m):
            bigger = v | {a ^ x for a in v}
            if bigger not in out:
                out.add(bigger)
                pending.append(bigger)
    return sorted(out, key=lambda v: (len(v), sorted(v)))


def cosets(v, m):
    unseen = set(range(1 << m))
    out = []
    while unseen:
        representative = min(unseen)
        block = frozenset(x ^ representative for x in v)
        out.append((representative, block))
        unseen -= block
    return out


def marginal(a, j):
    counts = Counter(x & j for x in a)
    return {x: F(n, len(a)) for x, n in counts.items()}


def run_transcript_case(a, b, m, seed):
    """Enumerate a bounded adaptive policy under the uniform null.

    A history-dependent query and stopping rule both see raw outcomes. The
    alternative probability of each null-compatible terminal path is calculated
    independently, not recovered from the claimed likelihood-ratio formula.
    """
    epsilon = F(1, 7)
    contexts = list(range(1, 1 << m))
    null_marginals = {j: marginal(a, j) for j in contexts}
    other_marginals = {j: marginal(b, j) for j in contexts}
    # history, null probability, alternative probability, informative queries
    pending = [((), F(1), F(1), 0)]
    terminal = []
    expected_informative_from_edges = F(0)
    while pending:
        history, p, q, k = pending.pop()
        state = seed + sum((i + 1) * (7 * j + 11 * x) for i, (j, x) in enumerate(history))
        depth = len(history)
        if depth == 4 or (depth >= 1 and (state + depth) % 5 == 0):
            terminal.append((history, p, q, k))
            continue
        j = contexts[(state + 3 * depth) % len(contexts)]
        p_j, r_j = null_marginals[j], other_marginals[j]
        informative = set(p_j).isdisjoint(r_j)
        assert informative or p_j == r_j
        expected_informative_from_edges += p * int(informative)
        for x, px in p_j.items():
            qx = (1 - epsilon) * px + epsilon * r_j.get(x, F(0))
            pending.append((history + ((j, x),), p * px, q * qx, k + informative))
    assert sum(p for _, p, _, _ in terminal) == 1
    assert sum(q for _, _, q, _ in terminal) <= 1
    for _, p, q, k in terminal:
        assert p / q == (1 / (1 - epsilon)) ** k
    expected_k = sum(p * k for _, p, _, k in terminal)
    assert expected_k == expected_informative_from_edges
    # This rational coefficient multiplies -log(1-epsilon) in transcript KL.
    return len(terminal), expected_k


counts = Counter()
for m in range(1, 4):
    for v in spaces(m):
        translated = cosets(v, m)
        for _, a in translated:
            for _, b in translated:
                if a == b:
                    continue
                for seed in range(5):
                    n, _ = run_transcript_case(a, b, m, seed)
                    counts['adaptive_policy_coset_cases'] += 1
                    counts['exact_terminal_likelihood_ratios'] += n

# Example A: equality relations on disjoint pairs, but opposite hidden coupling.
v = frozenset({0, 3, 12, 15})
positive = frozenset({0, 15})
negative = frozenset({3, 12})
assert all(marginal(positive, j) == marginal(negative, j) for j in (3, 12))
assert marginal(positive, 5) != marginal(negative, 5)
assert all((dot(3, x) == 0 and dot(12, x) == 0) == (x in v) for x in range(16))
# Classes generated by the two observed individual bits include their unobserved
# interaction. That interaction's expectation is +1 versus -1 in these laws.
assert F(sum((-1) ** dot(5, x) for x in positive), len(positive)) == 1
assert F(sum((-1) ** dot(5, x) for x in negative), len(negative)) == -1
counts['opposite_example_checks'] += 1

# Example B: singleton marginals determine an even-parity law by a 4x4 Walsh
# inverse, although even and odd parity cannot be distinguished by any pair.
even = frozenset(x for x in range(8) if dot(7, x) == 0)
odd = frozenset(range(8)) - even
assert all(marginal(even, j) == marginal(odd, j) for j in range(1, 7))
weights = dict(zip(sorted(even), (F(1, 10), F(2, 10), F(3, 10), F(4, 10))))
moments = {j: sum(p * (-1) ** dot(j, x) for x, p in weights.items()) for j in (0, 1, 2, 4)}
recovered = {x: sum(moments[j] * (-1) ** dot(j, x) for j in (0, 1, 2, 4)) / 4 for x in even}
assert recovered == weights
counts['opposite_example_checks'] += 1

out = {
    'scope': 'All ordered distinct affine coset pairs for all binary linear spaces in dimensions 1 through 3; five outcome-dependent query and stopping policies of horizon at most four per pair. Two independent opposite-example checks.',
    'arithmetic': 'Exact rational probabilities and stopped-transcript likelihood ratios. The result checks the coefficient of -log(1-epsilon), not a floating-point logarithm.',
    'totals': dict(counts),
    'all_assertions_passed': True,
}
Path(__file__).with_name('world_code_review_checks_results.json').write_text(json.dumps(out, indent=2) + '\n')
print(json.dumps(out, indent=2))
